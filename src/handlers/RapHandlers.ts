import { McpError, ErrorCode } from '@modelcontextprotocol/sdk/types.js';
import { BaseHandler } from './BaseHandler.js';
import type { ToolDefinition } from '../types/tools.js';
import type { RapGeneratorId, RapGeneratorContent } from 'abap-adt-api';

export class RapHandlers extends BaseHandler {
  getTools(): ToolDefinition[] {
    return [
      {
        name: 'scaffold_rap_bo',
        description:
          'Scaffold a complete managed RAP Business Object from a database table using the ' +
          'SAP RAP Generator API. Generates CDS root view, projection view, behavior definition, ' +
          'behavior implementation class, service definition, and service binding in one step. ' +
          'Artifact names are auto-generated by the SAP system. ' +
          'Pass transport="new" to create a TR automatically. ' +
          'Requires SAP S/4HANA 2022+ or S/4HANA Cloud.',
        inputSchema: {
          type: 'object',
          properties: {
            source_table: {
              type: 'string',
              description: 'Persistent database table name, e.g. ZCUSTOMER_D'
            },
            entity_label: {
              type: 'string',
              description: 'Business entity description used in artifact short texts, e.g. Customer'
            },
            package: {
              type: 'string',
              description: 'Target development package, e.g. Z_RAP_DEMO'
            },
            transport: {
              type: 'string',
              description: 'TR number to use, or "new" to create one automatically (default: "new")'
            },
            gen_id: {
              type: 'string',
              enum: ['uiservice', 'webapiservice'],
              description: '"uiservice" = OData V4 UI (default); "webapiservice" = Web API'
            },
            publish_service: {
              type: 'boolean',
              description: 'Publish the service binding immediately after generation (default: false)'
            }
          },
          required: ['source_table', 'entity_label', 'package']
        }
      },
      {
        name: 'replace_in_object',
        description:
          'Find-and-replace specific text inside an existing ABAP object source. ' +
          'Safer than setObjectSource for small targeted fixes — only touches the matched text.',
        inputSchema: {
          type: 'object',
          properties: {
            objectSourceUrl: {
              type: 'string',
              description: 'ADT source URL, e.g. /sap/bc/adt/programs/programs/zfoo/source/main'
            },
            objectUrl: {
              type: 'string',
              description: 'ADT object URL for locking, e.g. /sap/bc/adt/programs/programs/zfoo'
            },
            find: {
              type: 'string',
              description: 'Exact text to find'
            },
            replace_with: {
              type: 'string',
              description: 'Replacement text'
            },
            transport: {
              type: 'string',
              description: 'TR number'
            }
          },
          required: ['objectSourceUrl', 'objectUrl', 'find', 'replace_with', 'transport']
        }
      }
    ];
  }

  async handle(toolName: string, args: any): Promise<any> {
    switch (toolName) {
      case 'scaffold_rap_bo':
        return this.handleScaffoldRapBo(args);
      case 'replace_in_object':
        return this.handleReplaceInObject(args);
      default:
        throw new McpError(ErrorCode.MethodNotFound, `Unknown RAP tool: ${toolName}`);
    }
  }

  private ok(text: string) {
    return { content: [{ type: 'text', text }] };
  }

  private async writeSource(objectUrl: string, sourceUrl: string, source: string, transport: string): Promise<void> {
    const lock = await this.adtclient.lock(objectUrl);
    try {
      await this.adtclient.setObjectSource(sourceUrl, source, lock.LOCK_HANDLE, transport);
    } finally {
      await this.adtclient.unLock(objectUrl, lock.LOCK_HANDLE);
    }
  }

  async handleScaffoldRapBo(args: any): Promise<any> {
    const startTime = performance.now();
    const log: string[] = [];

    try {
      const pkg       = (args.package      as string).toUpperCase();
      const tableName = (args.source_table as string).toUpperCase();
      const tableUri  = `/sap/bc/adt/ddic/tables/${tableName.toLowerCase()}`;
      const genId: RapGeneratorId = (args.gen_id as RapGeneratorId) || 'uiservice';

      // ── 1. Availability check ────────────────────────────────────────────────
      const available = await this.adtclient.rapGenIsAvailable(genId);
      if (!available) {
        return this.ok(
          `RAP Generator (${genId}) is not available on this system.\n` +
          'This feature requires SAP S/4HANA 2022+ or S/4HANA Cloud.\n' +
          'Use the createObject + setObjectSource tools to scaffold manually.'
        );
      }
      log.push('✓ RAP Generator available');

      // ── 2. Initial validation (package exists, table is valid) ───────────────
      const initVal = await this.adtclient.rapGenValidateInitial(genId, tableUri, pkg);
      if (initVal.severity === 'error') {
        return this.ok(
          `Validation error: ${initVal.shortText}` +
          (initVal.longText ? `\n${initVal.longText}` : '')
        );
      }
      if (initVal.severity === 'warning') {
        log.push(`⚠ Warning: ${initVal.shortText}`);
      }
      log.push('✓ Initial validation passed');

      // ── 3. Get server-generated default content (artifact names, etc.) ───────
      let content: RapGeneratorContent = await this.adtclient.rapGenGetContent(genId, tableUri, pkg);
      log.push('✓ Got default content from server');

      // Apply user overrides
      content = {
        ...content,
        general: {
          ...content.general,
          description: (args.entity_label as string) || content.general.description,
          // Explicitly set referenceObjectName to avoid schema validation issues
          referenceObjectName: tableName
        },
        metadata: {
          ...content.metadata,
          package: pkg
        }
      };

      // ── 4. Ensure transport ──────────────────────────────────────────────────
      let transport: string = (args.transport as string) || 'new';
      if (transport === 'new') {
        transport = await this.adtclient.createTransport(
          tableUri,
          `RAP BO for ${tableName}`,
          pkg
        );
        log.push(`✓ Created TR ${transport}`);
      } else {
        log.push(`  Using TR ${transport}`);
      }

      // ── 5. Content validation (name collisions, field checks, etc.) ──────────
      const contentVal = await this.adtclient.rapGenValidateContent(genId, tableUri, content);
      if (contentVal.severity === 'error') {
        return this.ok(
          `Content validation failed: ${contentVal.shortText}` +
          (contentVal.longText ? `\n${contentVal.longText}` : '') +
          `\n\nProgress:\n${log.join('\n')}`
        );
      }
      if (contentVal.severity === 'warning') {
        log.push(`⚠ Content warning: ${contentVal.shortText}`);
      }
      log.push('✓ Content validation passed');

      // ── 6. Generate ──────────────────────────────────────────────────────────
      const generated = await this.adtclient.rapGenGenerate(genId, tableUri, transport, content);
      log.push(`✓ Generated ${generated.length} artifact(s):`);
      for (const obj of generated) {
        log.push(`   ${obj.type.padEnd(8)} ${obj.name}  — ${obj.description}`);
      }

      // ── 7. Optionally publish service binding ─────────────────────────────────
      const shouldPublish = args.publish_service === true || args.publish_service === 'true';
      const srvbName = content.businessService?.serviceBinding?.name;

      if (shouldPublish && srvbName) {
        const pubResult = await this.adtclient.rapGenPublishService(srvbName);
        if (pubResult.severity === 'error') {
          log.push(`⚠ Service binding publish failed: ${pubResult.shortText}`);
        } else {
          log.push(`✓ Service binding ${srvbName} published`);
        }
      } else if (srvbName) {
        log.push('');
        log.push('Next steps:');
        log.push(`  • Use publishServiceBinding to activate binding: ${srvbName}`);
        log.push('  • Or open Eclipse → Service Binding → Publish');
        log.push(`  • Refresh package ${pkg} (F5) in Eclipse to see new objects`);
      }

      this.trackRequest(startTime, true);
      return this.ok(log.join('\n'));

    } catch (error: any) {
      this.trackRequest(startTime, false);
      throw new McpError(
        ErrorCode.InternalError,
        `scaffold_rap_bo failed: ${error.message || 'Unknown error'}\n\nProgress:\n${log.join('\n')}`
      );
    }
  }

  async handleReplaceInObject(args: any): Promise<any> {
    const startTime = performance.now();
    try {
      const original = await this.adtclient.getObjectSource(args.objectSourceUrl);
      const src = typeof original === 'string' ? original : (original as any).source || '';

      if (!src.includes(args.find)) {
        return this.ok(`Text not found in object. Aborting.\nSearched for: ${args.find}`);
      }

      const occurrences = src.split(args.find).length - 1;
      const updated = src.split(args.find).join(args.replace_with);

      await this.writeSource(args.objectUrl, args.objectSourceUrl, updated, args.transport);

      this.trackRequest(startTime, true);
      return this.ok(
        `✓ Replaced ${occurrences} occurrence(s).\nFind:    ${args.find}\nReplace: ${args.replace_with}`
      );
    } catch (error: any) {
      this.trackRequest(startTime, false);
      throw new McpError(
        ErrorCode.InternalError,
        `replace_in_object failed: ${error.message || 'Unknown error'}`
      );
    }
  }
}
